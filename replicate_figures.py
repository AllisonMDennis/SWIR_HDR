def figure4ef(cfg):
    cal = cfg["calibration"]
    # Use the calibration CRF (recovered from the short exposures); do NOT
    # recompute. It is indexed from intensity 0 (variant-d denoised data).
    Sd, b, Smax, crf_short = load_calibration(cal["output_dir"])

    # Prefer CRFrecovery_full (0.25-8 s subset) if present, else checkerboard_long.
    long_dir = REPO_ROOT / "data/Images/CRFrecovery_full"
    if not long_dir.exists():
        long_dir = REPO_ROOT / "data/Images/CRFrecovery/checkerboard_long"
    long_dir = str(long_dir)

    # Long exposures, variant (d), sampled the same way as the calibration.
    l_img, l_t = step0.import_reflectance_data(long_dir)
    l_img, l_t = step0.sort_by_exposure_time(l_img, l_t)
    l_proc, l_zmax, l_zmin = preprocess_variant(l_img, l_t, Sd, b, Smax, "d")
    np.random.seed(SEED)
    l_isamp, l_logE, _, _, _ = step0.sampleIntensities(
        l_proc, l_t, l_zmax, l_zmin, step0._debevec)
    print(f"[Fig4e-f] long exposures: {len(l_t)} "
          f"{l_t.min():.3f}-{l_t.max():.3f}s  ({long_dir})")

    # Apply the existing short-exposure CRF to the long-exposure samples.
    stats = crf_fit_stats(crf_short, 0, l_isamp, l_logE, l_t)
    print(f"[Fig4e-f] short-CRF on long samples: R2={stats['r2']:.4f}  "
          f"n_used={stats['n_used']}")

    save_csv(pd.DataFrame({
        "pixel_intensity": stats["intensity"],
        "log_exposure":    stats["log_exposure"],
        "exposure_time":   stats["exposure_time"],
    }), "fig4ef_long_samples.csv")
    save_csv(pd.DataFrame({"r2": [stats["r2"]],
                           "n_samples": [stats["n_samples"]],
                           "n_used": [stats["n_used"]]}),
             "fig4ef_r2.csv")

    plot_crf_with_data(crf_short, stats,
                       "Fig 4e-f — short CRF on long exposures",
                       OUT / "fig4ef_long_crf.png")


