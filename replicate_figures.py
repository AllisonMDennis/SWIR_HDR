    # data/Images tree isn't polluted with large generated HDR_data files.
    base = str(OUT / f"{experiment_title}_HDR_data")

    processed = run_hdr(directory, experiment_title, base,
                        imp["preprocessing_ops"], params, crf,
                        step2.debevec, method="default")
    if not processed:
        raise RuntimeError("no ICG radiance map produced")

    rad_log = processed[0]["radiance_map"]      # log radiance
    rad_lin = np.exp(rad_log)
    np.save(OUT / "fig5_ICG_radiance.npy", rad_lin.astype(np.float32))

    pos = rad_lin[np.isfinite(rad_lin) & (rad_lin > 0)]
    dr_ratio = float(pos.max() / pos.min())
    dr_db = 20.0 * np.log10(dr_ratio)
    # Robust dynamic range over 1st-99th percentile signal.
    p1, p99 = np.percentile(pos, [1, 99])
    dr_db_robust = 20.0 * np.log10(p99 / p1)
    print(f"[Fig5] scene dynamic range: {dr_ratio:.3e}x  ({dr_db:.1f} dB full, "
          f"{dr_db_robust:.1f} dB 1-99 pct)")
    save_csv(pd.DataFrame({
        "metric": ["max", "min", "dr_ratio", "dr_dB", "dr_dB_1_99pct"],
        "value": [pos.max(), pos.min(), dr_ratio, dr_db, dr_db_robust]}),
        "fig5_dynamic_range.csv")

    fig, ax = plt.subplots(figsize=(6, 5))
    disp = np.log10(np.where(rad_lin > 0, rad_lin, np.nan))
    im = ax.imshow(disp, cmap="viridis")
    ax.set_title("Fig 5 — ICG plate HDR radiance (log10)")
    ax.axis("off")
    fig.colorbar(im, ax=ax, label="log10 radiance (a.u.)")
    fig.tight_layout(); fig.savefig(OUT / "fig5_ICG_radiance.png", dpi=200)
    plt.close(fig)


