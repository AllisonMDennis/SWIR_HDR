def load_calibration(calib_dir):
    """Load Sd, b, Smax, crf calibration arrays."""
    Sd   = np.load(os.path.join(calib_dir, "Sd.npy"))
    b    = np.load(os.path.join(calib_dir, "b.npy"))
    Smax = np.load(os.path.join(calib_dir, "Smax.npy"))
    crf  = np.load(os.path.join(calib_dir, "crf.npy"))
    return Sd, b, Smax, crf


def preprocess_variant(images, exposure_times, Sd, b, Smax, variant):
    """
    Produce (processed_images, Zmax, Zmin) for one CRF preprocessing variant.

        a : raw (no preprocessing)
        b : clip to Smax
        c : denoise (subtract per-pixel dark current Sd*t + b)
        d : clip to Smax AND denoise  (the manuscript choice; matches
            run_calibration in Step0_calibration)
    """
    n = len(exposure_times)
    H, W = Smax.shape
    images = images.astype(np.float32)
    DC = np.stack([Sd * t + b for t in exposure_times]).astype(np.float32)
    Smax_b = np.broadcast_to(Smax, (n, H, W)).astype(np.float32)

    if variant == "a":
        proc = images
        zmax = np.full((n, H, W), float(images.max()), np.float32)
        zmin = np.zeros((n, H, W), np.float32)
    elif variant == "b":
        # Constrain to both bounds: clip sub-noise pixels up to DC(t) and
        # saturated pixels down to Smax. Zmin = DC(t) shifts the tent midpoint
        # upward so sub-noise pixels get zero weight.
        proc = np.clip(images, DC, Smax_b).astype(np.float32)
        zmax = Smax_b.copy()
        zmin = DC.copy()
    elif variant == "c":
        proc = np.maximum(images - DC, 0).astype(np.float32)
        zmax = np.full((n, H, W), float(proc.max()), np.float32)
        zmin = np.zeros((n, H, W), np.float32)
    elif variant == "d":
        proc = np.maximum(np.minimum(images, Smax_b) - DC, 0).astype(np.float32)
        zmax = (Smax_b - DC).astype(np.float32)
        zmin = np.zeros((n, H, W), np.float32)
    else:
        raise ValueError(f"unknown variant {variant!r}")

    return proc, zmax, zmin


def recover_crf(proc, times, zmax, zmin, weighting, seed=SEED):
    """Sample intensities and solve for the camera response function (two-step)."""
    np.random.seed(seed)
    isamp, logE, srad, zmn, zmx = step0.sampleIntensities(
        proc, times, zmax, zmin, weighting)
    crf = step0.computeResponseCurve(
        isamp, logE, times, SMOOTHING_LAMBDA, weighting,
        zmn, zmx, zmax, zmin)
    return crf, isamp, logE


def crf_fit_stats(crf, crf_min, isamp, log_exposures, times):
    """
    Goodness-of-fit of a recovered CRF g(z): how well g(z_ij) predicts the
    pre-estimated log-exposures ln(Ê_i × t_j) returned by sampleIntensities.

    Residual = log_exposures[i,j] - g(z_ij), where g(z_ij) = crf[z_ij - crf_min].
    Points with pixel intensity 0 (denoised background) are excluded from R^2.
    crf_min is the intensity value that maps to crf[0].
    """
    idx = np.clip(np.round(isamp - crf_min).astype(int), 0, len(crf) - 1)
    g = crf[idx]                                   # (N, P) g(z_ij)
    resid = log_exposures - g                      # (N, P)

    mask = isamp > 0                               # exclude zero-intensity pixels
    L = log_exposures[mask]
    r = resid[mask]
    ss_res = float(np.sum(r ** 2))
    ss_tot = float(np.sum((L - L.mean()) ** 2))
    r2 = 1.0 - ss_res / ss_tot if ss_tot > 0 else float("nan")

    N, P = isamp.shape
    return {
        "r2": r2,
        "n_samples": N,
        "n_used": int(mask.sum()),
        "crf_min": crf_min,
        "isamp": isamp,                # (N, P) for per-exposure coloring
        "logE": log_exposures,         # (N, P)
        "resid": resid,                # (N, P)
        "times": times,
        # flattened for CSV export
        "intensity": isamp.flatten(),
        "log_exposure": log_exposures.flatten(),
        "exposure_time": np.tile(times, N),
    }


def plot_crf_with_data(crf, stats, title, png_path):
    """
    Manuscript Fig 4 layout: pixel intensity on the x-axis (log scale),
    log-exposure ln(Ê·t) on the y-axis. Sampled points are colored by exposure
    time so the per-exposure fanning is visible; the recovered CRF g(z) is
    overlaid (x = pixel intensity index, y = g(z)). Residuals below.
    """
    crf_min = stats["crf_min"]
    z_dom = np.arange(crf_min, crf_min + len(crf))
    isamp, logE, resid, times = (stats["isamp"], stats["logE"],
                                 stats["resid"], stats["times"])
    colors = plt.get_cmap("viridis")(np.linspace(0, 1, len(times)))

    fig, (ax0, ax1) = plt.subplots(
        2, 1, figsize=(6, 6), sharex=True,
        gridspec_kw={"height_ratios": [3, 1]})

    for j, t in enumerate(times):
        ax0.scatter(isamp[:, j], logE[:, j], s=3, alpha=0.3,
                    color=colors[j], label=f"{t:.3f}s")
    ax0.plot(z_dom, crf, "k-", lw=2, label="recovered CRF g(z)")
    ax0.set_xscale("log")
    ax0.set_ylabel(r"$\ln(\hat{E}\cdot t)$  (ln exposure)")
    ax0.set_title(f"{title}   (R$^2$={stats['r2']:.4f}, n={stats['n_used']})")
    ax0.legend(loc="best", fontsize=7, ncol=2)

    for j in range(len(times)):
        ax1.scatter(isamp[:, j], resid[:, j], s=3, alpha=0.3, color=colors[j])
    ax1.axhline(0, color="k", lw=1)
    ax1.set_xscale("log")
    ax1.set_xlabel("pixel intensity (DN)")
    ax1.set_ylabel("residual\n(ln units)")

    fig.tight_layout()
    fig.savefig(png_path, dpi=200)
    plt.close(fig)


def save_csv(df, name):
    path = OUT / name
    df.to_csv(path, index=False)
    return path


def hist_centers_counts(data, bins):
    counts, edges = np.histogram(data, bins=bins)
    centers = 0.5 * (edges[:-1] + edges[1:])
    return centers, counts


def run_hdr(directory, experiment_title, base_data_folder, operations,
            params, crf, weighting_fn, method):
    """
    Step 1 (import+preprocess) then Step 2 (HDR fusion). process_hdr_images
    chdir's into the data folder, so we restore cwd afterwards.
    """
    step1.process_and_save(directory, experiment_title, base_data_folder,
                           operations=operations, params=params)
    cwd = os.getcwd()
    try:
        processed = step2.process_hdr_images(
            directory, experiment_title, base_data_folder,
            coefficients_dict=params, response_curve=crf,
            weighting_function=weighting_fn, method=method)
    finally:
        os.chdir(cwd)
    return processed


def load_processed_stack(directory, base_data_folder, key):
    """Load the preprocessed (clip_denoise) image stack saved by Step 1."""
    folder = os.path.join(directory, base_data_folder, "processed_data")
    matches = glob.glob(os.path.join(folder, f"{key}_*.npy"))
    if not matches:
        return None, None
    data = np.load(matches[0], allow_pickle=True)
    return data["image"], data["exposure_time"]


