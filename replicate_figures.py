def figure4ad(cfg):
    cal = cfg["calibration"]
    Sd, b, Smax, _ = load_calibration(cal["output_dir"])
    crf_dir = str(REPO_ROOT / "data/Images/CRFrecovery/checkerboard_short")

    images, times = step0.import_reflectance_data(crf_dir)
    images, times = step0.sort_by_exposure_time(images, times)
    print(f"[Fig4a-d] checkerboard_short: {len(times)} exposures "
          f"{times.min():.3f}-{times.max():.3f}s")

    crfs = {}
    rows = []
    for v in ["a", "b", "c", "d"]:
        proc, zmax, zmin = preprocess_variant(images, times, Sd, b, Smax, v)
        crf, isamp, logE = recover_crf(proc, times, zmax, zmin, step0._debevec)
        crf_min = int(np.min(isamp))
        stats = crf_fit_stats(crf, crf_min, isamp, logE, times)
        crfs[f"crf_{v}"] = crf
        rows.append({"variant": v, "r2": stats["r2"],
                     "n_samples": stats["n_samples"], "n_used": stats["n_used"],
                     "crf_len": len(crf)})
        print(f"[Fig4{v}] R2={stats['r2']:.4f}  n_used={stats['n_used']}  "
              f"crf_len={len(crf)}")

        save_csv(pd.DataFrame({
            "pixel_intensity": stats["intensity"],
            "log_exposure":    stats["log_exposure"],
            "exposure_time":   stats["exposure_time"],
        }), f"fig4{v}_samples.csv")

        plot_crf_with_data(crf, stats, f"Fig 4{v} (variant {v})",
                           OUT / f"fig4{v}_crf.png")

    save_csv(pd.DataFrame(rows), "fig4_r2_summary.csv")
    np.savez(OUT / "fig4_crfs.npz", **crfs)


