def figure4g(cfg):
    cal = cfg["calibration"]
    Sd, b, Smax, _ = load_calibration(cal["output_dir"])
    crf_dir = str(REPO_ROOT / "data/Images/CRFrecovery/checkerboard_short")

    images, times = step0.import_reflectance_data(crf_dir)
    images, times = step0.sort_by_exposure_time(images, times)
    proc, zmax, zmin = preprocess_variant(images, times, Sd, b, Smax, "d")

    curves = {}   # name -> (z_domain, crf)
    saved = {}
    for name, wfn in WEIGHTS.items():
        crf, isamp, logE = recover_crf(proc, times, zmax, zmin, wfn)
        z0 = int(np.min(isamp))
        z_dom = np.arange(z0, z0 + len(crf))
        curves[name] = (z_dom, crf)
        saved[f"crf_{name}"] = crf
        saved[f"z_{name}"] = z_dom
        print(f"[Fig4g] {name}: crf_len={len(crf)}  "
              f"z=[{z_dom[0]}, {z_dom[-1]}]")

    np.savez(OUT / "fig4g_weighting_crfs.npz", **saved)

    # Max pairwise deviation on the common intensity domain.
    lo = max(z[0] for z, _ in curves.values())
    hi = min(z[-1] for z, _ in curves.values())
    z_common = np.arange(lo, hi + 1)
    interp = {n: np.interp(z_common, z, c) for n, (z, c) in curves.items()}
    names = list(interp)
    max_dev = 0.0
    for i in range(len(names)):
        for j in range(i + 1, len(names)):
            d = np.max(np.abs(interp[names[i]] - interp[names[j]]))
            max_dev = max(max_dev, d)
    print(f"[Fig4g] max pairwise CRF deviation (common domain) = {max_dev:.4f} ln units")

    df = pd.DataFrame({"pixel_intensity": z_common})
    for n in names:
        df[f"crf_{n}"] = interp[n]
    save_csv(df, "fig4g_weighting_crfs.csv")
    save_csv(pd.DataFrame({"max_pairwise_deviation_ln": [max_dev]}),
             "fig4g_max_deviation.csv")

    fig, ax = plt.subplots(figsize=(5, 4))
    for n, (z, c) in curves.items():
        ax.plot(z, c, lw=1.5, label=n)
    ax.set_xlabel("pixel intensity (DN)")
    ax.set_ylabel("g(z)  (ln exposure)")
    ax.set_title(f"Fig 4g — weighting functions\n(max dev {max_dev:.3f} ln units)")
    ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(OUT / "fig4g_weighting_overlay.png", dpi=200)
    plt.close(fig)


