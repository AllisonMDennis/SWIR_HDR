def figure3(cfg):
    cal = cfg["calibration"]
    Sd, b, Smax, _ = load_calibration(cal["output_dir"])

    print(f"[Fig3] Sd   mean={Sd.mean():.4f}  std={Sd.std():.4f}  (DN/s)")
    print(f"[Fig3] b    mean={b.mean():.4f}  std={b.std():.4f}  (DN)")
    print(f"[Fig3] Smax mean={Smax.mean():.4f}  std={Smax.std():.4f}  (DN)")

    # Per-pixel histograms for Prism
    for arr, name in [(Sd, "Sd"), (b, "b")]:
        centers, counts = hist_centers_counts(arr.flatten(), bins=100)
        save_csv(pd.DataFrame({"bin_center": centers, "count": counts}),
                 f"fig3_{name}_histogram.csv")

    # --- Mean dark current vs exposure, with the linear DC model overlaid ---
    dc_arr, dc_times = step0.import_darkcount_data(cal["dc_dir"])
    dc_arr, dc_times = step0.sort_by_exposure_time(dc_arr, dc_times)
    mean_dc = step0.analyze_darkcount_data(dc_arr, dc_times)["mean"]
    model_dc = Sd.mean() * dc_times + b.mean()

    save_csv(pd.DataFrame({"exposure_time": dc_times, "mean_DC": mean_dc,
                           "model_DC": model_dc}),
             "fig3_dc_vs_exposure.csv")

    fig, ax = plt.subplots(figsize=(5, 4))
    ax.scatter(dc_times, mean_dc, color="k", label="measured mean DC")
    ax.plot(dc_times, model_dc, "r-",
            label=f"linear model  Sd·t + b\n(Sd={Sd.mean():.2f}, b={b.mean():.1f})")
    ax.set_xlabel("exposure time (s)")
    ax.set_ylabel("mean dark current (DN)")
    ax.set_title("Fig 3 — dark current vs exposure")
    ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(OUT / "fig3_dc_vs_exposure.png", dpi=200)
    plt.close(fig)

    # --- Mean intensity vs exposure (log) with sensor-average sigmoid fit ---
    refl, refl_times = step0.import_reflectance_data(cal["reflectance_dir"])
    refl, refl_times = step0.sort_by_exposure_time(refl, refl_times)
    mean_int = refl.reshape(len(refl_times), -1).mean(axis=1)

    # Fit a single sigmoid to the spatially-averaged response ("sensor average").
    log_t = np.log10(refl_times)
    rng = mean_int.max() - mean_int.min()
    p0 = [rng, np.median(log_t), 0.5, mean_int.min()]
    bounds = ([0.1 * rng, log_t.min(), 0.1, mean_int.min()],
              [2.0 * rng, log_t.max(), 2.0, mean_int.max()])
    popt, _ = curve_fit(step0.sigmoid_curve, refl_times, mean_int,
                        p0=p0, bounds=bounds, maxfev=10000)
    a_, b_, c_, d_ = popt

    save_csv(pd.DataFrame({"exposure_time": refl_times, "mean_intensity": mean_int}),
             "fig3_intensity_vs_exposure.csv")
    save_csv(pd.DataFrame({"parameter": ["a", "b", "c", "d"], "value": popt}),
             "fig3_sigmoid_params.csv")
    print(f"[Fig3] sigmoid (sensor average): a={a_:.2f} b={b_:.3f} "
          f"c={c_:.3f} d={d_:.2f}")

    t_fine = np.logspace(np.log10(refl_times.min()), np.log10(refl_times.max()), 500)
    fig, ax = plt.subplots(figsize=(5, 4))
    ax.scatter(refl_times, mean_int, color="k", label="measured")
    ax.plot(t_fine, step0.sigmoid_curve(t_fine, *popt), "r-", label="sigmoid fit")
    ax.set_xscale("log")
    ax.set_xlabel("exposure time (s)")
    ax.set_ylabel("mean pixel intensity (DN)")
    ax.set_title("Fig 3 — saturation response")
    ax.legend(fontsize=8)
    fig.tight_layout(); fig.savefig(OUT / "fig3_intensity_vs_exposure.png", dpi=200)
    plt.close(fig)


