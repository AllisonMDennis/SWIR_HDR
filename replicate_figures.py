def _save_radiance_png(rad_log, title, path, log=True):
    fig, ax = plt.subplots(figsize=(6, 5))
    if log:
        disp = np.log10(np.where(np.exp(rad_log) > 0, np.exp(rad_log), np.nan))
        label = "log10 radiance (a.u.)"
    else:
        disp = np.exp(rad_log)
        label = "radiance (a.u.)"
    im = ax.imshow(disp, cmap="gray")
    ax.set_title(title); ax.axis("off")
    fig.colorbar(im, ax=ax, label=label)
    fig.tight_layout(); fig.savefig(path, dpi=200)
    plt.close(fig)


