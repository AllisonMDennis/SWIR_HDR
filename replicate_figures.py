FIGURES = {
    "3":    figure3,
    "4ad":  figure4ad,
    "4ef":  figure4ef,
    "4g":   figure4g,
    "5":    figure5,
    "6":    figure6,
}


def main():
    parser = argparse.ArgumentParser(description="Regenerate manuscript figure data.")
    parser.add_argument("--figure", default=None,
                        help="One of: 3, 4ad, 4ef, 4g, 5, 6 (default: all). "
                             "'--figure 4' runs all of 4ad/4ef/4g.")
    parser.add_argument("--config", default=None, help="Path to config.yaml")
    args = parser.parse_args()

    cfg = load_config(args.config)
    OUT.mkdir(exist_ok=True)

    if args.figure is None:
        todo = list(FIGURES.keys())
    elif args.figure == "4":
        todo = ["4ad", "4ef", "4g"]
    else:
        if args.figure not in FIGURES:
            parser.error(f"unknown figure {args.figure!r}; choose from "
                         f"{list(FIGURES)} or 4")
        todo = [args.figure]

    summary = {}
    for fig_id in todo:
        print("\n" + "=" * 60)
        print(f"  Figure {fig_id}")
        print("=" * 60)
        try:
            FIGURES[fig_id](cfg)
            summary[fig_id] = "OK"
        except Exception as e:
            summary[fig_id] = f"FAILED: {e}"
            traceback.print_exc()

    print("\n" + "=" * 60)
    print("  Summary")
    print("=" * 60)
    for fig_id in todo:
        print(f"  Figure {fig_id:5s} : {summary[fig_id]}")
    print(f"\nOutputs written to {OUT}")
    print("Figure 7 is not replicated (manual ROIs / line profiles).")


if __name__ == "__main__":
    main()
